export function getStoredLanguage() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === "zh" || saved === "en") return saved;
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function setStoredLanguage(language) {
  const normalized = language === "zh" ? "zh" : "en";
  localStorage.setItem(STORAGE_KEY, normalized);
  document.documentElement.lang = normalized === "zh" ? "zh-CN" : "en";
  return normalized;
}

export function createTranslator(language = getStoredLanguage()) {
  const lang = language === "zh" ? "zh" : "en";
  return function t(key, replacements = {}) {
    let value = messages[lang][key] || messages.en[key] || key;
    Object.entries(replacements).forEach(([name, replacement]) => {
      value = value.replaceAll(`{${name}}`, replacement);
    });
    return value;
  };
}

export function applyStaticTranslations(root = document, language = getStoredLanguage()) {
  const t = createTranslator(language);
  root.querySelectorAll("[data-i18n]").forEach(node => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(node => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-title]").forEach(node => {
    node.setAttribute("title", t(node.dataset.i18nTitle));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach(node => {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  });
}
